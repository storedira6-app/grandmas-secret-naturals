type I18nValue = {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (l: Lang) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    const stored = window.localStorage.getItem("gs-lang") as Lang | null;
    if (stored && stored in DICTS) setLangState(stored);
  }, []);

  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("gs-lang", l);
  }, []);

  const t = useCallback((key: string) => DICTS[lang][key] ?? DICTS.en[key] ?? key, [lang]);

  const value = useMemo(() => ({ lang, dir, setLang, t }), [lang, dir, setLang, t]) as I18nValue;

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/** Safe default so a component never crashes the page if it renders
 *  outside the provider (e.g. during a hot-reload remount). */
const FALLBACK_I18N = {
  lang: "ar" as Lang,
  dir: "rtl",
  setLang: () => {},
  t: (key: string) => DICTS.ar[key] ?? DICTS.en[key] ?? key,
} as unknown as I18nValue;

export function useI18n() {
  return useContext(I18nContext) ?? FALLBACK_I18N;
}

